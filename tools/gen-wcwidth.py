#!/usr/bin/env python3
"""Writes src/mosh/port/wcwidth_table.h from the C library's wcwidth().

Usage: tools/gen-wcwidth.py [output]

mosh's client must measure characters exactly as mosh-server does, or its
copy of the screen drifts from the server's. Servers are mostly Linux, where
mosh-server uses glibc's wcwidth(), so the table is taken from glibc itself
(in the C.UTF-8 locale) rather than derived from the Unicode data files.
Run it on a current glibc; the header records which one.
"""

import ctypes
import ctypes.util
import platform
import sys

LC_ALL = 6


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "src/mosh/port/wcwidth_table.h"
    libc = ctypes.CDLL(ctypes.util.find_library("c"))
    libc.setlocale.restype = ctypes.c_char_p
    if not libc.setlocale(LC_ALL, b"C.UTF-8"):
        sys.exit("the C.UTF-8 locale isn't available")
    libc.wcwidth.argtypes = [ctypes.c_uint32]
    libc.wcwidth.restype = ctypes.c_int
    libc.gnu_get_libc_version.restype = ctypes.c_char_p
    version = libc.gnu_get_libc_version().decode()

    runs = {-1: [], 0: [], 2: []}
    start, prev = 0, libc.wcwidth(0)
    for cp in range(1, 0x110001):
        w = libc.wcwidth(cp) if cp <= 0x10FFFF else None
        if w != prev:
            if prev in runs:
                runs[prev].append((start, cp - 1))
            start, prev = cp, w

    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/gen-wcwidth.py from wcwidth() of glibc %s (%s) in\n" % (version, platform.machine()))
        f.write("// the C.UTF-8 locale. Do not edit; run the script again instead.\n")
        f.write("// Code points not listed are one column wide.\n\n")
        f.write("#pragma once\n\n")
        for name, w in (("nonprinting", -1), ("zero_width", 0), ("double_width", 2)):
            f.write("// wcwidth() == %d\n" % w)
            f.write("static const struct MoshWidthRange mosh_%s[] = {\n" % name)
            items = ["{0x%04X, 0x%04X}" % r for r in runs[w]]
            for i in range(0, len(items), 6):
                f.write("    " + ", ".join(items[i:i + 6]) + ",\n")
            f.write("};\n\n")


if __name__ == "__main__":
    main()
